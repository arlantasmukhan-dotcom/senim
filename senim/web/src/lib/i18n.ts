export const DICTS: Record<Lang, Dict> = { ru, kk, en };
export const LANGS: Lang[] = ["kk", "ru", "en"];
export const LANG_COOKIE = "senim.lang";

export function parseLang(v: string | undefined): Lang {
  return v === "kk" || v === "en" ? v : "ru";
}

export const LANG_LABEL: Record<Lang, string> = { kk: "KZ", ru: "RU", en: "EN" };
export type { Tone };

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** forms: [one, few, many]. Kazakh and English only look at one vs other. */
export function plural(lang: Lang, n: number, forms: string[]): string {
  if (lang === "ru") {
    const m10 = n % 10;
    const m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return forms[0];
    if (m10 >= 2 && m10 <= 4 && !(m100 >= 12 && m100 <= 14)) return forms[1];
    return forms[2];
  }
  return n === 1 ? forms[0] : forms[1];
}

export function formatInt(lang: Lang, n: number): string {
  return new Intl.NumberFormat(lang === "en" ? "en-US" : "ru-RU").format(n).replace(/ /g, " ");
}

/** Server-written explanations predate the UI style rules: drop pictographs and long dashes. */
export function tidy(s: string): string {
  return s
    .replace(/[\p{Extended_Pictographic}️]/gu, "")
    .replace(/\s+[—–]\s+/g, ", ")
    .replace(/[—–]/g, "-")
    .replace(/\s{2,}/g, " ")
    .trim();
}

